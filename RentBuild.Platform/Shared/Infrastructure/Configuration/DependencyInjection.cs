        services.AddScoped<IMaintenanceQueryService, MaintenanceQueryService>();
        services.AddScoped<IIdentityContextFacade, IdentityContextFacade>();
        services.AddScoped<IProfilesContextFacade, ProfilesContextFacade>();
        services.AddScoped<IInventoryContextFacade, InventoryContextFacade>();
        services.AddScoped<ISubscriptionsContextFacade, SubscriptionsContextFacade>();
